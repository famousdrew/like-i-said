#!/usr/bin/env python3
"""Assemble the copy-paste prompts and the Claude skill from their sources.

    python3 tools/build.py           write prompts/ and skill/voice-bible/
    python3 tools/build.py --check   exit 1 if any generated file is out of date

Sources:  src/prompts/*.md, src/skill/SKILL.md, reference/, templates/,
          tools/voice_stats.py, tools/check_quotes.py, tools/check_invented.py
Outputs:  prompts/*.md (all but README.md) and everything under skill/voice-bible/

A source prompt pulls in another file with a line like one of these:

    {{include: reference/ai-tells.md}}
    {{include: reference/interview-questions.md from "## Part 1"}}

The second form includes the file from the first line that starts with the quoted text.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skill" / "voice-bible"
INCLUDE = re.compile(r'^\{\{include: (?P<path>\S+?)(?: from "(?P<start>[^"]+)")?\}\}$', re.M)
HAND_WRITTEN = {ROOT / "prompts" / "README.md"}


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def expand(text: str, source: Path) -> str:
    def include(match: "re.Match[str]") -> str:
        target = ROOT / match["path"]
        if not target.is_file():
            raise SystemExit("%s includes a missing file: %s" % (source, match["path"]))
        body = read(target)
        if match["start"]:
            lines = body.split("\n")
            for index, line in enumerate(lines):
                if line.startswith(match["start"]):
                    body = "\n".join(lines[index:])
                    break
            else:
                raise SystemExit('%s: no line in %s starts with "%s"' % (
                    source, match["path"], match["start"]))
        return body.strip()

    out = INCLUDE.sub(include, text)
    if "{{include" in out:
        raise SystemExit("%s has an include line this script could not read" % source)
    return out


def outputs() -> "dict[Path, str]":
    files: "dict[Path, str]" = {}
    for source in sorted((ROOT / "src" / "prompts").glob("*.md")):
        text = expand(read(source), source)
        files[ROOT / "prompts" / source.name] = text
        files[SKILL / "references" / source.name] = text
    files[SKILL / "SKILL.md"] = read(ROOT / "src" / "skill" / "SKILL.md")
    for script in ("voice_stats.py", "check_quotes.py", "check_invented.py"):
        files[SKILL / "scripts" / script] = read(ROOT / "tools" / script)
    return files


def existing() -> "set[Path]":
    found = {p for p in (ROOT / "prompts").glob("*.md")} - HAND_WRITTEN
    if SKILL.exists():
        found |= {p for p in SKILL.rglob("*") if p.is_file() and "__pycache__" not in p.parts
                  and p.name != ".DS_Store"}
    return found


def main(argv: "list[str] | None" = None) -> int:
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    wanted = outputs()
    stale = [p for p, text in wanted.items() if not p.is_file() or read(p) != text]
    extra = sorted(existing() - set(wanted))
    if check:
        for path in stale:
            print("out of date: %s" % path.relative_to(ROOT))
        for path in extra:
            print("not generated by the build: %s" % path.relative_to(ROOT))
        if stale or extra:
            print("Run: python3 tools/build.py")
            return 1
        print("Generated files are up to date.")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    for path in extra:
        path.unlink()
        print("removed %s" % path.relative_to(ROOT))
    print("Wrote %d files (%d changed)." % (len(wanted), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
